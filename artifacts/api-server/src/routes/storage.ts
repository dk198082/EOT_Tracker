import { Readable } from 'stream';
import {
  RequestUploadUrlBody,
  RequestUploadUrlResponse,
} from '@workspace/api-zod';
import { Router, type IRouter, type Request, type Response } from 'express';

import { requireAuth } from '../middlewares/requireAuth';
import { ObjectStorageService } from '../lib/objectStorage';
import { recordPendingUpload } from '../lib/pendingUploads';
import type { User } from '@workspace/db';

const MAX_FILE_SIZE = 50 * 1024 * 1024; // 50 MB

const ALLOWED_CONTENT_TYPES = new Set([
  'application/pdf',
  'image/jpeg',
  'image/png',
  'image/gif',
  'image/webp',
  'image/svg+xml',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.ms-powerpoint',
  'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  'text/plain',
  'text/csv',
  'application/zip',
  'application/octet-stream',
]);

const router: IRouter = Router();
const objectStorageService = new ObjectStorageService();

/**
 * POST /storage/uploads/request-url
 *
 * Request a presigned URL for file upload, scoped to an ETO request.
 * Records a pending-upload token so attachment creation can verify that
 * the storageKey was minted by this user for this ETO — preventing
 * cross-user key reuse and arbitrary-path injection.
 */
router.post(
  '/storage/uploads/request-url',
  requireAuth,
  async (req: Request, res: Response) => {
    const user = res.locals.dbUser as User;

    const parsed = RequestUploadUrlBody.safeParse(req.body);
    if (!parsed.success) {
      res.status(400).json({ error: 'Missing or invalid required fields' });
      return;
    }

    const { name, size, contentType, etoRequestId } = parsed.data;

    // Server-side size limit
    if (size > MAX_FILE_SIZE) {
      res.status(400).json({ error: `File exceeds maximum allowed size of ${MAX_FILE_SIZE / (1024 * 1024)} MB` });
      return;
    }

    // Server-side content-type allowlist
    if (!ALLOWED_CONTENT_TYPES.has(contentType)) {
      res.status(400).json({ error: `File type '${contentType}' is not allowed` });
      return;
    }

    try {
      const uploadURL = await objectStorageService.getObjectEntityUploadURL();
      const objectPath = objectStorageService.normalizeObjectEntityPath(uploadURL);

      // Bind this presigned URL to the requesting user and ETO
      recordPendingUpload(objectPath, {
        userId: user.id,
        etoRequestId,
        contentType,
        fileSize: size,
      });

      res.json(
        RequestUploadUrlResponse.parse({
          uploadURL,
          objectPath,
          metadata: { name, size, contentType, etoRequestId },
        }),
      );
    } catch (error) {
      req.log.error({ err: error }, 'Error generating upload URL');
      res.status(500).json({ error: 'Failed to generate upload URL' });
    }
  },
);

/**
 * GET /storage/public-objects/*
 *
 * Serve public assets from PUBLIC_OBJECT_SEARCH_PATHS.
 * These are unconditionally public — no authentication or ACL checks.
 * IMPORTANT: Always provide this endpoint when object storage is set up.
 */
router.get(
  '/storage/public-objects/*filePath',
  async (req: Request, res: Response) => {
    try {
      const raw = req.params.filePath;
      const filePath = Array.isArray(raw) ? raw.join('/') : raw;
      const file = await objectStorageService.searchPublicObject(filePath);
      if (!file) {
        res.status(404).json({ error: 'File not found' });
        return;
      }

      const response = await objectStorageService.downloadObject(file);

      res.status(response.status);
      response.headers.forEach((value, key) => res.setHeader(key, value));

      if (response.body) {
        const nodeStream = Readable.fromWeb(
          response.body as ReadableStream<Uint8Array>,
        );
        nodeStream.pipe(res);
      } else {
        res.end();
      }
    } catch (error) {
      req.log.error({ err: error }, 'Error serving public object');
      res.status(500).json({ error: 'Failed to serve public object' });
    }
  },
);

// NOTE: Private object serving (/storage/objects/*) is intentionally omitted.
// Attachments are accessed exclusively via short-lived signed download URLs
// generated by GET /api/eto-requests/:id/attachments/:attachmentId/download,
// which enforces authentication. Direct object streaming would bypass that
// access control entirely.

export default router;
